const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const auth = read('src/contexts/AuthContext.tsx');
const rules = read('firestore.rules');
const service = read('src/services/firmService.ts');
const ui = read('src/components/dashboard/admin/AdminCompaniesView.tsx');
const signup = auth.slice(auth.indexOf('const signUpWithEmail'), auth.indexOf('// Google Sign-In'));
const onboarding = auth.slice(auth.indexOf('const completeOnboarding'), auth.indexOf('// Regular user profile'));
assert(!signup.includes('firmService.createCompany('), 'Public signup must not provision tenants');
assert(!onboarding.includes('firmService.createCompany('), 'Profile recovery must not provision tenants');
assert.match(signup, /profileData\.requestedBusinessNumber/);
assert.match(onboarding, /profileData\.requestedBusinessNumber/);
assert.match(signup, /profileData\.membershipStatus = 'PENDING_COMPANY_VERIFICATION'/);
assert.match(onboarding, /profileData\.membershipStatus = 'PENDING_COMPANY_VERIFICATION'/);
const companies = rules.slice(rules.indexOf('match /companies/{companyId}'), rules.indexOf('match /company_directory/{companyId}'));
assert.match(companies, /allow create: if isAdmin\(\) && canAccessTaggedBranch\(request\.resource\.data\)/);
const directory = rules.slice(rules.indexOf('match /company_directory/{companyId}'), rules.indexOf('match /workers/{workerId}'));
assert.match(directory, /allow create: if isAdmin\(\) && adminBranchId\(\) != ''/);
assert.match(service, /await runTransaction\(db, async \(transaction\) =>/);
assert.match(service, /transaction\.set\(companyRef/);
assert.match(service, /transaction\.set\(directoryRef/);
assert.match(service, /transaction\.update\(userRef/);
assert.match(ui, /approveCompanyRegistration/);
assert.match(ui, /지부 선택/);
console.log('PASS phase19 signup/approval structural checks (NOT emulator or UI runtime verification)');
