const assert = require('node:assert/strict');
const fs = require('node:fs');
const rules=fs.readFileSync('firestore.rules','utf8');
const company=rules.split('match /companies/{companyId} {')[1].split('\n    // Phase 9:')[0];
const editable=company.match(/affectedKeys\(\)\.hasOnly\(\[([\s\S]*?)\]\)/)?.[1];
assert.ok(editable,'company representative field allowlist missing');
for(const key of ['companyName','contactEmail','contactPhone','address'])assert.ok(editable.includes(`'${key}'`),key);
for(const key of ['subscription','currentPlanId','branchId','ownerId','activeSubscriptionRequestId','status','role','isAdmin','billingInfo'])assert.ok(!editable.includes(`'${key}'`),key);
const retired=rules.split('match /subscription_requests/{requestId} {')[1];
assert.match(retired,/allow create, update, delete: if false/);
const service=fs.readFileSync('src/services/subscriptionRequestService.ts','utf8');
const creation=service.split('async createSubscriptionRequest(')[1].split('async getSubscriptionRequestsByCompany(')[0];
assert.match(creation,/throw new Error\('온라인 플랜 변경 신청은 종료되었습니다/);
assert.doesNotMatch(creation,/runTransaction\(/);
const ui=fs.readFileSync('src/components/dashboard/admin/AdminSubscriptionsView.tsx','utf8');
assert.match(ui,/isValidPlanDate\(cleanStart\)/);
const dateHelper=fs.readFileSync('src/utils/planDates.ts','utf8');
assert.match(dateHelper,/parsed.toISOString\(\).slice\(0, 10\) === value/);
assert.match(rules,/request.time < timestamp.date\(/);
console.log('PASS: company privilege allowlist, retired plan writes, strict dates, exclusive expiry boundary');
