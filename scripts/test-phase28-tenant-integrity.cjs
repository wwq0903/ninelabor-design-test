const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const service = read('src/services/firmService.ts');
const rules = read('firestore.rules');
const dir = rules.slice(rules.indexOf('match /company_directory/{companyId}'), rules.indexOf('match /workers/{workerId}'));
const create = service.slice(service.indexOf('async createCompany('), service.indexOf('async updateCompany('));
const approval = service.slice(service.indexOf('async approveCompanyRegistration('), service.indexOf('async searchPublicCompanies('));
assert.match(approval, /currentBranch !== branchId/, 'Approval must be restricted to admin branch');
assert.match(approval, /applicant\.branchId && applicant\.branchId !== branchId/, 'Existing applicant branch must not be reassigned');
assert.match(create, /transaction\.get\(docRef\)/, 'Check existing tenant before creation');
assert.match(create, /existing\.exists\(\)/, 'Reject existing tenant IDs');
assert.match(create, /transaction\.set\(docRef, newCompany\)/, 'Tenant write must be transactional');
assert.match(create, /transaction\.set\(directoryRef, directoryEntry\)/, 'Directory write must be in same transaction');
assert.doesNotMatch(create, /await setDoc\(docRef, newCompany\)/, 'No partial non-transactional creation');
assert.match(dir, /existsAfter\(/, 'Atomic tenant creation requires after-state lookup');
assert.match(dir, /getAfter\(/, 'Directory create must use after-state tenant branch');
assert.match(dir, /adminCanAccessCompany\(companyId\)/, 'Directory changes must be branch-scoped');
assert.doesNotMatch(dir, /getUserData\(\)\.role == 'COMPANY'/, 'Company must not forge public directory entries');
assert.match(service, /const actorRole: UserRole = 'ADMIN'/, 'Audit role must not be caller supplied');
console.log('PASS phase28 tenant creation, approval, directory isolation, audit actor role (static assertions only)');
